def _shift(date_str, days=1):
    return (dt.date.fromisoformat(date_str) + dt.timedelta(days=days)).isoformat()


def _rewrite(day, pairs):
    s = json.dumps(day, ensure_ascii=False)
    for old, new in pairs:
        o, n = json.dumps(old, ensure_ascii=False)[1:-1], json.dumps(new, ensure_ascii=False)[1:-1]
        assert o in s, f"2/1版：書き換え元が見つかりません（DAY{day['n']}）：{old[:40]}"
        s = s.replace(o, n)
    return json.loads(s)


