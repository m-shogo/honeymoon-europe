import fs from 'node:fs';import assert from 'node:assert/strict';
const load=x=>JSON.parse(fs.readFileSync(new URL('../data/'+x,import.meta.url),'utf8'));
const model=load('itinerary-16days.json'),short=load('itinerary-14days.json'),audit=load('duration-audit.json');
assert.equal(model.days.length,16);
assert.deepEqual(model.days.map(x=>x.day),Array.from({length:16},(_,i)=>i+1));
assert.equal(model.days.filter(x=>x.type==='full_sightseeing').length,10,'10 full sightseeing days required');
assert.equal(model.days.filter(x=>x.type==='intercity_transfer').length,3,'Intercity transfers need three separate days');
assert.equal(model.days.filter(x=>x.type==='international_return_departure').length,1);
assert.equal(model.days.filter(x=>x.type==='international_return_arrival').length,1);
assert.equal(model.days[15].phase,'日本到着・帰宅');
assert.ok(model.days[12].items.some(e=>e.spot_ids.includes('061')),'Mont Saint Michel must be retained');
assert.ok(model.days[5].items.some(e=>e.spot_ids.includes('062')),'Mouth of Truth must be retained');
assert.ok(model.days[8].items.some(e=>e.spot_ids.includes('063')),'Gondola option must be retained');
for(const code of ['060','061','062'])assert.ok(model.preference_spot_ids.must_visit.includes(code),'Must visit missing '+code);
assert.ok(model.preference_spot_ids.optional.includes('063'));
assert.equal(short.days.length,14);
assert.ok(short.days[13].type==='international_return_arrival');
assert.equal(audit.total_days_required,16);
assert.equal(Object.values(audit.components).reduce((a,b)=>a+b,0),16);
console.log('OK: 16日 full sightseeing + 14日 compressed, departures/arrivals and all must-see stops verified');
